-- Student Scholarship Monitoring & Academic Compliance System
-- Supabase schema. Run this in the Supabase SQL editor, then connect the app
-- from the "Backend Connection" panel (Staff view).

create table if not exists public.scholars (
  student_id text primary key,
  name        text not null,
  program     text not null,
  policy      text not null check (policy in ('Merit Scholar', 'Community Scholar')),
  created_at  timestamptz not null default now()
);

create table if not exists public.submissions (
  id            bigint primary key generated by default as identity,
  student_id    text not null references public.scholars(student_id) on delete cascade,
  ay            text not null,
  sem           text not null,
  gwa           numeric(4,2) not null check (gwa between 1.00 and 5.00),
  units         integer not null check (units >= 1),
  failed        integer not null default 0 check (failed >= 0),
  inc           integer not null default 0 check (inc >= 0),
  dropped       integer not null default 0 check (dropped >= 0),
  proof         text not null,
  verification  text not null default 'Pending' check (verification in ('Pending', 'Verified', 'Returned')),
  compliance    text not null default 'Pending' check (compliance in ('Pending', 'Compliant', 'With Deficiency')),
  reason        text not null default '',
  feedback      text not null default '',
  renewal       text not null default 'Pending' check (renewal in ('Pending', 'Approved', 'Held')),
  renewal_at    timestamptz,
  renewal_note  text not null default '',
  submitted_at  timestamptz not null default now()
);

create index if not exists submissions_student_idx on public.submissions(student_id);
create index if not exists submissions_submitted_idx on public.submissions(submitted_at desc);

alter table public.scholars enable row level security;
alter table public.submissions enable row level security;

-- Demo policies: the anon key can read/write directly.
-- Replace these with authenticated, role-scoped policies before production use.
drop policy if exists "anon read scholars" on public.scholars;
create policy "anon read scholars" on public.scholars for select to anon, authenticated using (true);
drop policy if exists "anon write scholars" on public.scholars;
create policy "anon write scholars" on public.scholars for insert to anon, authenticated with check (true);
drop policy if exists "anon update scholars" on public.scholars;
create policy "anon update scholars" on public.scholars for update to anon, authenticated using (true) with check (true);
drop policy if exists "anon delete scholars" on public.scholars;
create policy "anon delete scholars" on public.scholars for delete to anon, authenticated using (true);

drop policy if exists "anon read submissions" on public.submissions;
create policy "anon read submissions" on public.submissions for select to anon, authenticated using (true);
drop policy if exists "anon write submissions" on public.submissions;
create policy "anon write submissions" on public.submissions for insert to anon, authenticated with check (true);
drop policy if exists "anon update submissions" on public.submissions;
create policy "anon update submissions" on public.submissions for update to anon, authenticated using (true) with check (true);
drop policy if exists "anon delete submissions" on public.submissions;
